"""Renders the C header's declarations and their doc comments as Markdown.

The header is generated by cbindgen from the Rust sources, with `//` comment blocks above each
declaration. The page is rebuilt from that header every time, so it matches the shipped ABI."""

import re
from pathlib import Path

DEFINE = re.compile(r"^#define\s+(\w+)(\(.*?\))?\s*(.*)$")


def find_header(root: Path):
    for pattern in ("bindings/c/include/*.h", "include/*.h"):
        found = sorted(p for p in root.glob(pattern) if not p.name.endswith("_go.h"))
        if found:
            return found[0]
    return None


def parse(text: str):
    """Yield (kind, name, comment, declaration) for each documented declaration."""
    items, comment, decl, depth = [], [], [], 0
    for raw in text.splitlines():
        line = raw.rstrip()
        if not decl:
            if line.startswith("//"):
                comment.append(line[2:].strip())
                continue
            if not line.strip():
                if comment and not decl:
                    pass
                continue
            if line.startswith("#define"):
                m = DEFINE.match(line)
                if m and m.group(3).strip():
                    items.append(("macro", m.group(1), comment, line))
                comment = []
                continue
            if line.startswith("#") or line.startswith("extern") or line.startswith("}") or line.startswith("/*"):
                comment = []
                continue
        decl.append(line)
        depth += line.count("{") - line.count("}") + line.count("(") - line.count(")")
        if depth <= 0 and line.rstrip().endswith(";"):
            body = "\n".join(decl)
            items.append((_kind(body), _name(body), comment, body))
            comment, decl, depth = [], [], 0
    return items


def _kind(body: str) -> str:
    if body.startswith("typedef"):
        return "type"
    return "function"


def _name(body: str) -> str:
    if body.startswith("typedef"):
        m = re.search(r"(\w+)\s*;\s*$", body)
        return m.group(1) if m else "type"
    m = re.search(r"(\w+)\s*\(", body)
    return m.group(1) if m else "declaration"


def _prose(comment):
    """Comment lines to Markdown: blank lines separate paragraphs, `# Heading` becomes bold."""
    paragraphs, current = [], []
    for line in comment + [""]:
        if line.startswith("# "):
            line = f"**{line[2:].strip()}**"
            if current:
                paragraphs.append(" ".join(current))
                current = []
            paragraphs.append(line)
        elif line:
            current.append(line)
        elif current:
            paragraphs.append(" ".join(current))
            current = []
    return "\n\n".join(paragraphs)


def render(header: Path, version: str = "") -> str:
    items = parse(header.read_text(encoding="utf-8"))
    out = [
        "---",
        'description: "The C ABI of Holographic Memory, rendered from the shipped header."',
        "---",
        "",
        "# C API reference",
        "",
        f"Rendered from `{header.name}`, the header the library ships. Every symbol carries the ABI "
        "major version as a suffix, so a program built against one major version keeps working with "
        "later minor versions of the library.",
        "",
    ]
    for title, kind in (("Macros", "macro"), ("Types", "type"), ("Functions", "function")):
        group = [i for i in items if i[0] == kind]
        if not group:
            continue
        out += [f"## {title}", ""]
        for _, name, comment, body in group:
            out += [f"### `{name}`", ""]
            if comment:
                out += [_prose(comment), ""]
            out += ["```c", body, "```", ""]
    return "\n".join(out).rstrip() + "\n"
