"""Land regenerated benchmark files through a short-lived bot branch.

Commits are created with the GraphQL `createCommitOnBranch` mutation, so GitHub signs them (the
repository requires verified signatures); the branch is opened as a PR, squash-merged and
deleted. Needs `gh` and GH_TOKEN. Merging past the review requirement needs a token that may
bypass it (secret BENCH_BOT_TOKEN); with the default workflow token the PR is opened and left
for a maintainer, and the reason is printed.
"""

import argparse
import base64
import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]


def gh(*args, payload=None):
    out = subprocess.run(["gh", *args], input=payload, capture_output=True, text=True, cwd=ROOT)
    if out.returncode:
        raise RuntimeError(f"gh {' '.join(args[:3])} failed: {out.stderr.strip()[-600:]}")
    return out.stdout.strip()


def changed(paths):
    out = subprocess.run(["git", "status", "--porcelain", "--untracked-files=all", "--", *paths], capture_output=True, text=True, cwd=ROOT, check=True)
    files = []
    for line in out.stdout.splitlines():
        status, name = line[:2], line[3:]
        if "D" in status:
            raise RuntimeError(f"refusing to land a deletion: {name}")
        files.append(name)
    return files


def land(branch, title, body, paths, merge, base="main"):
    files = changed(paths)
    if not files:
        print("no changes to land")
        return 0
    repo = os.environ["GITHUB_REPOSITORY"]
    head = gh("api", f"repos/{repo}/git/ref/heads/{base}", "--jq", ".object.sha")
    gh("api", "-X", "POST", f"repos/{repo}/git/refs", "-f", f"ref=refs/heads/{branch}", "-f", f"sha={head}")
    try:
        additions = [{"path": f, "contents": base64.b64encode((ROOT / f).read_bytes()).decode()} for f in files]
        mutation = ("mutation($input: CreateCommitOnBranchInput!) { createCommitOnBranch(input: $input) { commit { oid } } }")
        variables = {"input": {"branch": {"repositoryNameWithOwner": repo, "branchName": branch},
                               "message": {"headline": title, "body": body}, "expectedHeadOid": head,
                               "fileChanges": {"additions": additions}}}
        gh("api", "graphql", "--input", "-", payload=json.dumps({"query": mutation, "variables": variables}))
        url = gh("pr", "create", "--base", base, "--head", branch, "--title", title, "--body", body)
        print(url)
        if merge:
            gh("pr", "merge", url, "--squash", "--admin", "--delete-branch")
            print("merged and deleted", branch)
        else:
            print("left open: no BENCH_BOT_TOKEN, so checks and the review requirement need a maintainer", file=sys.stderr)
    except Exception:
        subprocess.run(["gh", "api", "-X", "DELETE", f"repos/{repo}/git/refs/heads/{branch}"], capture_output=True, cwd=ROOT)
        raise
    return 0


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--branch", required=True)
    p.add_argument("--title", required=True)
    p.add_argument("--body", default="Regenerated by .github/workflows/bench-refresh.yml.")
    p.add_argument("--merge", action="store_true")
    p.add_argument("paths", nargs="+")
    a = p.parse_args()
    return land(a.branch, a.title, a.body, a.paths, a.merge)


if __name__ == "__main__":
    sys.exit(main())
